-- 1. Tables ------------------------------------------------------------------

-- A "model" row is one headshot shoot: selfies (samples), the chosen AI model,
-- and the generated images.
CREATE TABLE IF NOT EXISTS public.models (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at    timestamptz NOT NULL DEFAULT now(),
  user_id       uuid REFERENCES auth.users(id) ON DELETE CASCADE,
  name          text,
  type          text,
  status        text NOT NULL DEFAULT 'processing',  -- processing | finished | failed
  "modelId"     text,
  ai_model      text,
  styles        text[] NOT NULL DEFAULT '{}',
  credits_used  integer NOT NULL DEFAULT 0,
  error         text,
  outfit        jsonb                               -- optional suit/shirt/tie choices
);
CREATE INDEX IF NOT EXISTS models_user_id_idx ON public.models (user_id);

CREATE TABLE IF NOT EXISTS public.samples (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at  timestamptz NOT NULL DEFAULT now(),
  "modelId"   bigint NOT NULL REFERENCES public.models(id) ON DELETE CASCADE,
  uri         text NOT NULL
);
CREATE INDEX IF NOT EXISTS samples_model_id_idx ON public.samples ("modelId");

CREATE TABLE IF NOT EXISTS public.images (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at  timestamptz NOT NULL DEFAULT now(),
  "modelId"   bigint NOT NULL REFERENCES public.models(id) ON DELETE CASCADE,
  uri         text NOT NULL
);
CREATE INDEX IF NOT EXISTS images_model_id_idx ON public.images ("modelId");

-- One row per fal.ai queue request (one per selected style).
CREATE TABLE IF NOT EXISTS public.generation_requests (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  model_id    bigint NOT NULL REFERENCES public.models(id) ON DELETE CASCADE,
  request_id  text NOT NULL UNIQUE,
  endpoint    text NOT NULL,
  style       text,
  num_images  integer NOT NULL DEFAULT 1,
  status      text NOT NULL DEFAULT 'pending',  -- pending | saving | done | failed
  error       text
);
CREATE INDEX IF NOT EXISTS generation_requests_model_id_idx ON public.generation_requests (model_id);

CREATE TABLE IF NOT EXISTS public.credits (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at  timestamptz NOT NULL DEFAULT now(),
  user_id     uuid NOT NULL UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
  credits     integer NOT NULL DEFAULT 0
);

-- 2. Row Level Security --------------------------------------------------------
-- Users can only READ their own data. All writes go through the server
-- (service role key), which bypasses RLS.

ALTER TABLE public.models              ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.samples             ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.images              ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.generation_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.credits             ENABLE ROW LEVEL SECURITY;

-- Policies are dropped first so this script is safe to re-run.
-- Column references inside the subqueries are table-qualified on purpose:
-- models has its own "modelId" (text) column, so an unqualified "modelId"
-- would resolve to models."modelId" instead of samples/images."modelId".

DROP POLICY IF EXISTS "Users read own models" ON public.models;
CREATE POLICY "Users read own models" ON public.models
  FOR SELECT TO authenticated USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users delete own models" ON public.models;
CREATE POLICY "Users delete own models" ON public.models
  FOR DELETE TO authenticated USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users read own samples" ON public.samples;
CREATE POLICY "Users read own samples" ON public.samples
  FOR SELECT TO authenticated
  USING (auth.uid() = (SELECT m.user_id FROM public.models m WHERE m.id = samples."modelId"));

DROP POLICY IF EXISTS "Users read own images" ON public.images;
CREATE POLICY "Users read own images" ON public.images
  FOR SELECT TO authenticated
  USING (auth.uid() = (SELECT m.user_id FROM public.models m WHERE m.id = images."modelId"));

DROP POLICY IF EXISTS "Users read own generation requests" ON public.generation_requests;
CREATE POLICY "Users read own generation requests" ON public.generation_requests
  FOR SELECT TO authenticated
  USING (auth.uid() = (SELECT m.user_id FROM public.models m WHERE m.id = generation_requests.model_id));

DROP POLICY IF EXISTS "Users read own credits" ON public.credits;
CREATE POLICY "Users read own credits" ON public.credits
  FOR SELECT TO authenticated USING (auth.uid() = user_id);

GRANT USAGE ON SCHEMA public TO authenticated, service_role;
GRANT SELECT, DELETE ON public.models TO authenticated;
GRANT SELECT ON public.samples, public.images, public.generation_requests, public.credits TO authenticated;
GRANT ALL ON public.models, public.samples, public.images, public.generation_requests, public.credits TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;

-- 3. Credit functions (atomic; server only) ------------------------------------

-- Returns the new balance, or NULL if the user doesn't have enough credits.
CREATE OR REPLACE FUNCTION public.deduct_credits(p_user_id uuid, p_amount integer)
RETURNS integer
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  UPDATE public.credits
     SET credits = credits - p_amount
   WHERE user_id = p_user_id
     AND p_amount >= 0
     AND credits >= p_amount
  RETURNING credits;
$$;

-- Adds credits (purchases, refunds), creating the row if needed.
CREATE OR REPLACE FUNCTION public.add_credits(p_user_id uuid, p_amount integer)
RETURNS integer
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  INSERT INTO public.credits (user_id, credits)
  VALUES (p_user_id, GREATEST(p_amount, 0))
  ON CONFLICT (user_id)
  DO UPDATE SET credits = public.credits.credits + GREATEST(p_amount, 0)
  RETURNING credits;
$$;

REVOKE ALL ON FUNCTION public.deduct_credits(uuid, integer) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.add_credits(uuid, integer)    FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.deduct_credits(uuid, integer) TO service_role;
GRANT EXECUTE ON FUNCTION public.add_credits(uuid, integer)    TO service_role;

-- 4. Realtime (live status + credit balance in the dashboard) ------------------
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_publication_tables
                 WHERE pubname = 'supabase_realtime' AND tablename = 'models') THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.models;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_publication_tables
                 WHERE pubname = 'supabase_realtime' AND tablename = 'credits') THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.credits;
  END IF;
END $$;
