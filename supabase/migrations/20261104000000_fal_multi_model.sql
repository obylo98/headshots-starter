-- Switch from Astria training to fal.ai multi-model generation.
-- A row in "models" is now a headshot "shoot": the user's selfies (samples),
-- the AI model they picked, and the generated images.

-- 1. Extra columns on models
ALTER TABLE "public"."models"
  ADD COLUMN IF NOT EXISTS "ai_model" text,
  ADD COLUMN IF NOT EXISTS "styles" text[] NOT NULL DEFAULT '{}',
  ADD COLUMN IF NOT EXISTS "credits_used" integer NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS "error" text;

-- 2. One row per fal.ai queue request (one per selected style)
CREATE TABLE IF NOT EXISTS "public"."generation_requests" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "created_at" timestamp with time zone DEFAULT now() NOT NULL,
  "updated_at" timestamp with time zone DEFAULT now() NOT NULL,
  "model_id" bigint NOT NULL REFERENCES "public"."models"("id") ON DELETE CASCADE,
  "request_id" text NOT NULL UNIQUE,
  "endpoint" text NOT NULL,
  "style" text,
  "num_images" integer NOT NULL DEFAULT 1,
  -- pending -> saving -> done | failed
  "status" text NOT NULL DEFAULT 'pending',
  "error" text
);

CREATE INDEX IF NOT EXISTS "generation_requests_model_id_idx"
  ON "public"."generation_requests" ("model_id");

ALTER TABLE "public"."generation_requests" ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Owners can read their generation requests" ON "public"."generation_requests";
CREATE POLICY "Owners can read their generation requests"
  ON "public"."generation_requests" FOR SELECT TO "authenticated"
  USING (auth.uid() = (SELECT m.user_id FROM public.models m WHERE m.id = generation_requests.model_id));

-- 3. Credits can only be changed by the server (service role).
--    Previously a signed-in user could UPDATE/INSERT their own credits row
--    from the browser and grant themselves free credits.
DROP POLICY IF EXISTS "Enable update for authenticated users" ON "public"."credits";
DROP POLICY IF EXISTS "Enable insert for authenticated users only" ON "public"."credits";

CREATE UNIQUE INDEX IF NOT EXISTS "credits_user_id_key" ON "public"."credits" ("user_id");

-- Atomically deduct credits. Returns the new balance, or NULL if the user
-- does not have enough credits (nothing is deducted in that case).
CREATE OR REPLACE FUNCTION public.deduct_credits(p_user_id uuid, p_amount integer)
RETURNS integer
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  UPDATE public.credits
     SET credits = credits - p_amount
   WHERE user_id = p_user_id
     AND p_amount >= 0
     AND credits >= p_amount
  RETURNING credits;
$$;

-- Atomically add credits (refunds and purchases), creating the row if needed.
CREATE OR REPLACE FUNCTION public.add_credits(p_user_id uuid, p_amount integer)
RETURNS integer
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  INSERT INTO public.credits (user_id, credits)
  VALUES (p_user_id, GREATEST(p_amount, 0))
  ON CONFLICT (user_id)
  DO UPDATE SET credits = public.credits.credits + GREATEST(p_amount, 0)
  RETURNING credits;
$$;

REVOKE ALL ON FUNCTION public.deduct_credits(uuid, integer) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.add_credits(uuid, integer) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.deduct_credits(uuid, integer) TO service_role;
GRANT EXECUTE ON FUNCTION public.add_credits(uuid, integer) TO service_role;
