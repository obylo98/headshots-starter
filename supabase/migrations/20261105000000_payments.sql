-- Payments ledger + exactly-once credit grants (Paystack and Stripe).
-- Run in Supabase > SQL Editor. Safe to re-run.

CREATE TABLE IF NOT EXISTS public.payments (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at  timestamptz NOT NULL DEFAULT now(),
  user_id     uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  provider    text NOT NULL,           -- 'paystack' | 'stripe'
  reference   text NOT NULL,           -- Paystack reference / Stripe session id
  amount      bigint NOT NULL,         -- smallest unit (kobo / cents)
  currency    text NOT NULL,
  credits     integer NOT NULL,
  pack_id     text,
  UNIQUE (provider, reference)
);
CREATE INDEX IF NOT EXISTS payments_user_id_idx ON public.payments (user_id);

ALTER TABLE public.payments ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Users read own payments" ON public.payments;
CREATE POLICY "Users read own payments" ON public.payments
  FOR SELECT TO authenticated USING (auth.uid() = user_id);

GRANT SELECT ON public.payments TO authenticated;
GRANT ALL ON public.payments TO service_role;

-- Records the payment and adds its credits in one transaction.
-- Returns TRUE if credits were granted now, FALSE if this payment was
-- already processed (e.g. webhook and redirect both arrived).
CREATE OR REPLACE FUNCTION public.grant_payment_credits(
  p_user_id uuid,
  p_provider text,
  p_reference text,
  p_amount bigint,
  p_currency text,
  p_credits integer,
  p_pack_id text DEFAULT NULL
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  inserted_id bigint;
BEGIN
  IF p_credits <= 0 THEN
    RAISE EXCEPTION 'credits must be positive';
  END IF;

  INSERT INTO public.payments (user_id, provider, reference, amount, currency, credits, pack_id)
  VALUES (p_user_id, p_provider, p_reference, p_amount, p_currency, p_credits, p_pack_id)
  ON CONFLICT (provider, reference) DO NOTHING
  RETURNING id INTO inserted_id;

  IF inserted_id IS NULL THEN
    RETURN false;
  END IF;

  INSERT INTO public.credits (user_id, credits)
  VALUES (p_user_id, p_credits)
  ON CONFLICT (user_id)
  DO UPDATE SET credits = public.credits.credits + p_credits;

  RETURN true;
END;
$$;

REVOKE ALL ON FUNCTION public.grant_payment_credits(uuid, text, text, bigint, text, integer, text)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.grant_payment_credits(uuid, text, text, bigint, text, integer, text)
  TO service_role;
